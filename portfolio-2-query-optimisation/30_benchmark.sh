#!/usr/bin/env bash
# =====================================================================
# MIT 8103 Portfolio 2: before/after benchmark
#
#   1. Reset to the baseline (10_reset_baseline.sql)
#   2. Run every queries/qN_before.sql: 1 warm-up + RUNS timed runs
#   3. Apply the optimisations (20_optimise.sql)
#   4. Run every queries/qN_after.sql the same way
#   5. Write the execution plans and results/summary.md
#
# Timing = "Execution Time" reported by EXPLAIN (ANALYZE, BUFFERS).
# The median of the timed runs is used, so one slow run does not
# distort the result. The cache is warm for both phases (fair test).
#
# Run (after 00_load_large_data.sh):
#   bash portfolio-2-query-optimisation/30_benchmark.sh
# =====================================================================
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
Q="$HERE/queries"
OUT="$HERE/results"
RUNS="${RUNS:-7}"
mkdir -p "$OUT"

psql_nrs() { docker exec -i nrs_postgres psql -X -v ON_ERROR_STOP=1 -q -U nrs_admin -d nrs_tax_db "$@"; }

# Print the EXPLAIN ANALYZE plan of a query file.
# Optional PRE_SQL (e.g. a SET command) runs first in the same session.
explain() {
  { echo "SET search_path TO nrs; ${PRE_SQL:-}"; echo "EXPLAIN (ANALYZE, BUFFERS)"; cat "$1"; } | psql_nrs
}

# Median "Execution Time" (ms) over $RUNS runs. Saves the last plan to $2.
time_query() {
  local file="$1" plan_out="$2" times=() t
  explain "$file" > /dev/null                         # warm-up run
  for _ in $(seq "$RUNS"); do
    explain "$file" > "$plan_out" 2>&1 || true
    t=$(grep -E "Execution Time" "$plan_out" | grep -oE "[0-9]+\.[0-9]+" || true)
    [ -n "$t" ] || { echo "ERROR: no timing for $1 (see $plan_out)" >&2; exit 1; }
    times+=("$t")
  done
  printf '%s\n' "${times[@]}" | sort -n | awk '{a[NR]=$1} END {print a[int((NR+1)/2)]}'
}

write_cost() {   # Execution Time of inserting 50,000 payments (rolled back)
  local plan_out="$1" times=() t
  for _ in 1 2 3; do
    { echo "SET search_path TO nrs;"; cat "$Q/write_cost.sql"; } | psql_nrs > "$plan_out" 2>&1 || true
    t=$(grep -E "Execution Time" "$plan_out" | grep -oE "[0-9]+\.[0-9]+" || true)
    [ -n "$t" ] || { echo "ERROR: no timing for $1 (see $plan_out)" >&2; exit 1; }
    times+=("$t")
  done
  printf '%s\n' "${times[@]}" | sort -n | awk '{a[NR]=$1} END {print a[int((NR+1)/2)]}'
}

TIMES="$OUT/.times"; : > "$TIMES"
get() { awk -v q="$1" -v k="$2" '$1==q && $2==k {print $3}' "$TIMES"; }
up() { echo "$1" | tr a-z A-Z; }
QUERIES=(q1 q2 q3 q4 q5 q6)

echo "== Phase 1: baseline =="
psql_nrs < "$HERE/10_reset_baseline.sql"
for q in "${QUERIES[@]}"; do
  t=$(time_query "$Q/${q}_before.sql" "$OUT/${q}_before_plan.txt")
  echo "$q before $t" >> "$TIMES"
  echo "  $q before: $t ms"
done
WRITE_BEFORE=$(write_cost "$OUT/write_cost_before_plan.txt")
echo "  write cost before: $WRITE_BEFORE ms"

echo "== Phase 2: applying optimisations =="
psql_nrs < "$HERE/20_optimise.sql"

echo "== Phase 3: optimised =="
for q in "${QUERIES[@]}"; do
  t=$(time_query "$Q/${q}_after.sql" "$OUT/${q}_after_plan.txt")
  echo "$q after $t" >> "$TIMES"
  echo "  $q after:  $t ms"
done
# Extra experiment: the new index exists, but Q3 is NOT rewritten.
Q3_INDEX_ONLY=$(time_query "$Q/q3_before.sql" "$OUT/q3_index_not_rewritten_plan.txt")
echo "  q3 index but old SQL: $Q3_INDEX_ONLY ms"
WRITE_AFTER=$(write_cost "$OUT/write_cost_after_plan.txt")
echo "  write cost after: $WRITE_AFTER ms"

# Index sizes
SIZES=$(psql_nrs -A -F ' | ' -t <<'SQL'
SELECT '| ' || c.relname, pg_size_pretty(pg_relation_size(c.oid)) || ' |'
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'nrs'
  AND c.relname IN ('idx_individual_name','idx_taxpayer_email_lower','idx_return_type_filing',
                    'idx_payment_date_cover','idx_return_review_queue','mv_taxpayer_balance',
                    'idx_mv_balance_id','idx_mv_balance_owed')
ORDER BY pg_relation_size(c.oid) DESC;
SQL
)

# Main plan node of a plan file = first line that mentions a scan
scan_nodes() { grep -oE "(Parallel )?(Seq|Index Only|Index|Bitmap Heap|Bitmap Index) Scan( using [a-z_]+)? on [a-z_]+" "$1" | sort -u | paste -sd ';' - | sed 's/;/; /g'; }

{
  echo "# Benchmark results"
  echo
  echo "Generated by \`30_benchmark.sh\` on $(date '+%Y-%m-%d %H:%M'). Median of $RUNS runs after 1 warm-up run."
  echo "PostgreSQL 16 in Docker, $(psql_nrs -At -c 'SELECT count(*) FROM nrs.taxpayer') taxpayers, $(psql_nrs -At -c 'SELECT count(*) FROM nrs.tax_return') returns, $(psql_nrs -At -c 'SELECT count(*) FROM nrs.payment') payments."
  echo
  echo "| Query | Before (ms) | After (ms) | Speed-up |"
  echo "|---|---:|---:|---:|"
  for q in "${QUERIES[@]}"; do
    b=$(get "$q" before); a=$(get "$q" after)
    echo "| $(up "$q") | $b | $a | $(awk -v b="$b" -v a="$a" 'BEGIN {r=b/a; if (r<10) printf "%.1f×", r; else printf "%.0f×", r}') |"
  done
  echo
  echo "Extra experiment:"
  echo
  echo "- Q3 with the new index but the OLD (EXTRACT) SQL: **$Q3_INDEX_ONLY ms**"
  echo
  echo "## Access paths"
  echo
  echo "| Query | Before | After |"
  echo "|---|---|---|"
  for q in "${QUERIES[@]}"; do
    echo "| $(up "$q") | $(scan_nodes "$OUT/${q}_before_plan.txt") | $(scan_nodes "$OUT/${q}_after_plan.txt") |"
  done
  echo
  echo "## Write cost (insert 50,000 payments, rolled back)"
  echo
  echo "| State | Time (ms) |"
  echo "|---|---:|"
  echo "| Baseline indexes | $WRITE_BEFORE |"
  echo "| + idx_payment_date_cover | $WRITE_AFTER |"
  echo
  echo "## Storage used by the optimisations"
  echo
  echo "| Object | Size |"
  echo "|---|---:|"
  echo "$SIZES"
} > "$OUT/summary.md"

echo
cat "$OUT/summary.md"
rm -f "$TIMES"
